import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

// Keep the source modules independently testable. The browser downloads a single
// program; the existing loaders still decide when each module can safely run.
const root = new URL('../', import.meta.url);
const read = file => readFileSync(new URL(file, root), 'utf8');
const modules = [
  'sales-pace.js', 'data-reliability.js', 'bootstrap-v36.js', 'v16-legacy.js', 'shared-v31.js',
  'master-upload-v34.js', 'upload-diff-v99.js', 'kpi-layout-v37.js',
  'upper-history-v39.js', 'vendor-mbo-gap-v43.js', 'vendor-close-ui-v67.js',
  'boundary-forecast-v113.js', 'forecast-progress-v81.js', 'group-info-no-mbo-v82.js',
  'group-no-mbo-final-v87.js', 'export-v21.js', 'ui-streamline-v46.js',
  'vendor-excel-format-v48.js', 'detail-shell-v61.js', 'final-layout-v53.js',
  'unified-loader-v74.js', 'visual-polish-v74.js', 'decision-radar-v93.js',
  'master-text-editor-v95.js', 'unified-final-v73.js',
];
const entries = ['month-labels-v112.js', 'v16.js', 'export-v19.js', 'pwa-install.js', 'work-hub-link.js'];
const factory = file => `${JSON.stringify(file)}: function () {\n${read(file)}\n}`;
const bundle = [
  '/* Generated by node scripts/pack-dashboard.mjs from the dashboard sources. */',
  '(() => {',
  `window.__sfBundledScripts = {\n${modules.map(factory).join(',\n')}\n};`,
  ...entries.map(file => `/* ${file} */\n${read(file)}\n;`),
  '})();\n',
].join('\n');
const key = content => createHash('sha256').update(content).digest('hex').slice(0, 12);
const page = read('index.html');
const rendered = page.replace(/sales-dashboard\.js\?v=[\w-]+/, `sales-dashboard.js?v=${key(bundle)}`)
  .replace(/dashboard-quality\.css\?v=[\w-]+/, `dashboard-quality.css?v=${key(read('dashboard-quality.css'))}`);
if (!rendered.includes(`sales-dashboard.js?v=${key(bundle)}`)) throw Error('Dashboard entry is missing');
if (process.argv.includes('--check')) {
  if (read('sales-dashboard.js') !== bundle || page !== rendered) throw Error('Rebuild with node scripts/pack-dashboard.mjs before deploying');
} else {
  writeFileSync(new URL('sales-dashboard.js', root), bundle);
  writeFileSync(new URL('index.html', root), rendered);
}
