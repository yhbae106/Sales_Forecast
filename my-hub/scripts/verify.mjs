import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
import {validateCatalog} from '../src/storage.js';
import {tracked} from './build.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const metadata=JSON.parse(read('build-meta.json'));
assert.equal(metadata.version,1,'Unsupported build metadata');
for(const name of [...tracked,'hub.js'])assert.equal(createHash('sha256').update(read(name)).digest('hex'),metadata.hashes[name],`${name} differs from verified build. Run npm run build in my-hub.`);
const catalog=validateCatalog(JSON.parse(read('catalog.json')));
for(const url of ['https://yhbae106.github.io/Sales_Forecast/','https://yhbae106.github.io/SLA_DCM_2026_DW/','https://yhbae106.github.io/Gigo/'])assert(catalog.some(b=>b.url===url),`Missing default connection: ${url}`);
const html=read('index.html');
for(const [,asset] of html.matchAll(/(?:src|href)="\.\/([^"?]+)(?:\?[^\"]*)?"/g))assert(fs.existsSync(path.join(root,asset)),`Missing asset ${asset}`);
assert(!read('hub.js').includes('/api/boards'),'Static build must not depend on the former server API');
assert(!read('hub.js').includes('/signin-with-chatgpt'),'Static build must not depend on the former sign-in route');
const result=spawnSync(process.execPath,['--test',path.join(root,'src/storage.test.js')],{encoding:'utf8'});
process.stdout.write(result.stdout||'');process.stderr.write(result.stderr||'');
assert.equal(result.status,0,'MY HUB behavioral tests failed');
console.log('MY HUB HARNESS PASS: build integrity, catalog, assets and storage behaviors');
